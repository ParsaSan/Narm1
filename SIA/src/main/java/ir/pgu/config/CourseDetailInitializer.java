    private void seed(String code, String schedule, String location, String about, String chapters) {
        courseRepository.findAll().stream()
                .filter(c -> code.equals(c.getCode()))
                .findFirst()
                .ifPresent(c -> {
                    CourseDetail d = new CourseDetail();
                    d.setCourseId(c.getId());
                    d.setSchedule(schedule);
                    d.setLocation(location);
                    d.setAbout(about);
                    d.setChapters(chapters);
                    detailRepository.save(d);
                });
    }
